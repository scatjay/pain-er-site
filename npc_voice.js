  function forPersona(p) {
    if (!p) return null;
    if (V[p.id]) return V[p.id];
    if (p.core === false && p.title && p.title.indexOf('其他病患') === 0) {
      var mood = (p.bio || '').match(/心情：([^。]+)/); var k = mood ? mood[1] : '有點焦躁';
      return { lines: V.generic[k] || V.generic['有點焦躁'], escalation: V.generic._escalation, tells: [], src: V.generic.src };
    }
    return null;
  }
  /* 注入提示詞用：三小段，總長控制在 ~600 字內（代理程式只取提示的前 6000 字） */
  function promptLines(p) {
    var v = forPersona(p); if (!v) return [];
    var out = ['【你常說的話（可以直接用，也可以改成當下的說法；不要每句都用）】' + (v.lines || []).slice(0, 6).join('／')];
    if (v.escalation) out.push('【你會怎麼升溫或降溫】' + v.escalation);
    if (v.tells && v.tells.length) out.push('【別人看得到的小動作，必要時用括號描寫】' + v.tells.join('、'));
    return out;
  }
  return { VOICE: V, forPersona: forPersona, promptLines: promptLines };
