  function forPersona(p) {
    if (!p) return null;
    if (V[p.id]) return V[p.id];
    if (p.core === false && p.title && p.title.indexOf('其他病患') === 0) {
      var mood = (p.bio || '').match(/心情：([^。]+)/); var k = mood ? mood[1] : '有點焦躁';
      return { lines: V.generic[k] || V.generic['有點焦躁'], escalation: V.generic._escalation, tells: [], src: V.generic.src };
    }
    return null;
  }
